// CAT: new file (M2-R8 kasf library). The exe keeps HW1 kas2c's FunctionCall rows (tools/kas2c/kas2c.h: name[129],
//      returnsNumber, realName[129], numParams, 16 FunctionParam {name[129], type}; 0x990 bytes a row, 486 rows and a
//      "*" sentinel); this table keeps the same fields as pointers plus each row's name hash (cat_kasHashString
//      0x00491860, the dispatcher's case constant) and the exe address of the kasf the dispatcher
//      cat_kasCallFunctionByName 0x0045b9a0 calls for it. KASFuncTable.c is GENERATED by tools/m2_kasf_table_gen.py.

#ifndef ___KASFUNCTABLE_H
#define ___KASFUNCTABLE_H

#include "Types.h"

#define CAT_KAS_FUNCTION_COUNT      486     // rows before the "*" sentinel
#define CAT_KAS_FUNCTION_MAX_PARAMS 16      // kas2c MAX_FUNC_PARAMS

// kas2c's parameter types, in kas2c.h's order (the table's type words)
typedef enum
{
    KAS_PARAM_SBYTE,
    KAS_PARAM_UBYTE,
    KAS_PARAM_SWORD,
    KAS_PARAM_UWORD,
    KAS_PARAM_SDWORD,
    KAS_PARAM_UDWORD,           // CAT: a KAS name hash (timers, variables, messages, labels), not a string
    KAS_PARAM_REAL32,
    KAS_PARAM_REAL64,
    KAS_PARAM_BOOL,
    KAS_PARAM_BOOL8,
    KAS_PARAM_BOOL16,
    KAS_PARAM_SHIPPTR,
    KAS_PARAM_GROWSELECTIONPTR,
    KAS_PARAM_AITEAMPTR,
    KAS_PARAM_CHARPTR,
    KAS_PARAM_PATHPTR,
    KAS_PARAM_VECTORPTR,
    KAS_PARAM_VOLUMEPTR
} CatKasParamType;

typedef struct CatKasFunctionParam
{
    const char *name;
    sdword type;                // CatKasParamType
} CatKasFunctionParam;

typedef struct CatKasFunction
{
    const char *name;           // the KAS name (+0x000 of the exe's row)
    udword hash;                // cat_kasHashString(name) (not in the exe's row: the dispatcher's case constant)
    sdword returnsNumber;       // +0x084
    const char *realName;       // the kasf (+0x088)
    sdword numParams;           // +0x10C
    CatKasFunctionParam params[CAT_KAS_FUNCTION_MAX_PARAMS];   // +0x110, 0x88 bytes each in the exe
    udword exeAddress;          // the kasf's address in cataclysm.exe (from the dispatcher; not in the exe's row)
} CatKasFunction;

extern const CatKasFunction cat_kasFunctionTable[CAT_KAS_FUNCTION_COUNT + 1];

sdword cat_kasCallFunctionByName(char *name, void **args);     // 0x0045b9a0 (KASFuncDispatch.c, generated)

#endif
