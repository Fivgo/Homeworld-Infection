/*=============================================================================
    Name    : SaveCat32.c
    Purpose : CAT: reading cataclysm.exe's saves (version 0x10ad0027) on an LP64
              build: each ILP32 struct chunk is converted field by field into
              this tree's native struct (tables generated by
              tools/m2_save32_gen.py into SaveCat32Layouts.c), and the tree's
              own load and fix-up code then runs on the native chunk, in the
              order of the exe's PreLoadGame 0x004fdfc0 and LoadGame 0x004fe0e0
              (SaveGame.c). Pointers in the exe's dumps are object IDs, player
              indices, list positions, NULL or stale pointers; they are
              sign-extended into the native pointer slots, where the Fix* code
              reads them back as sdwords, as GoK's 64-bit loader does with its
              own saves (docs/m2-r6-oracle-mode-a.md "loader").

    Created 2026-10-18 for Homeworld-Infection (M2-R6 oracle-mode-a). This
    tree is REULA-licensed, see src/COPYING.REULA.
=============================================================================*/

