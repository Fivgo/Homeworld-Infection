/*-----------------------------------------------------------------------------
    Name        : saveCat32Convert
    Description : converts one struct: every op of the generated table, in order (where a union's 64-bit views
                  overlap, the later member's write wins; SaveCat32Layouts.c lists those unions). Bytes no op
                  writes (padding, and the tails the 64-bit layout adds) keep what dst64 held.
    Inputs      : layout, src32 (layout->size32 bytes)
    Outputs     : dst64 (layout->size64 bytes)
----------------------------------------------------------------------------*/
void saveCat32Convert(const SaveCat32Layout *layout, const void *src32, void *dst64)
{
    const ubyte *src = (const ubyte *)src32;
    ubyte *dst = (ubyte *)dst64;
    const SaveCat32Op *op;
    udword i, k;
    sdword s;
    uword w;
    int64_t v;

    for (i = 0; i < layout->nops; i++)
    {
        op = &layout->ops[i];
        switch (op->kind)
        {
            case SC32_COPY:
                memcpy(dst + op->off64, src + op->off32, op->n);
                break;

            case SC32_PTR:
                for (k = 0; k < op->count; k++)
                {
                    memcpy(&s, src + op->off32 + 4 * k, 4);
                    v = (int64_t)s;                         // an ID of -1 stays -1 when read back as an sdword
                    memcpy(dst + op->off64 + 8 * k, &v, 8);
                }
                break;

            case SC32_SEXT:
            case SC32_ZEXT:
                for (k = 0; k < op->count; k++)
                {
                    if (op->s32 == 2)
                    {
                        memcpy(&w, src + op->off32 + 2 * k, 2);
                        v = (op->kind == SC32_SEXT) ? (int64_t)(sword)w : (int64_t)w;
                    }
                    else
                    {
                        memcpy(&s, src + op->off32 + 4 * k, 4);
                        v = (op->kind == SC32_SEXT) ? (int64_t)s : (int64_t)(udword)s;
                    }
                    memcpy(dst + op->off64 + op->s64 * k, &v, op->s64);    // little-endian: the low bytes
                }
                break;

            case SC32_ARRAY:
                for (k = 0; k < op->count; k++)
                {
                    saveCat32Convert(op->sub, src + op->off32 + op->s32 * k, dst + op->off64 + op->s64 * k);
                }
                break;

            default:
                dbgFatalf(DBG_Loc, "saveCat32Convert: bad op %u in %s", (unsigned)op->kind, layout->name);
                break;
        }
    }
}

const SaveCat32Layout *saveCat32SpecLayout(CustShipHeader *header)
{
    const SaveCat32SpecLayout *e;

    for (e = saveCat32SpecLayouts; e->header != NULL; e++)
    {
        if (e->header == header)
        {
            return e->spec;
        }
    }
    return NULL;
}

static void saveCat32Problem(const char *what, sdword got, sdword want)
{
    saveCat32Problems++;
    dbgMessagef("Cataclysm save: %s: %d bytes, expected %d", what, (int)got, (int)want);
}

static SaveChunk *saveCat32NewChunk(SaveChunk *old, sdword size64)
{
    SaveChunk *chunk = memAlloc(sizeofSaveChunk(size64), "cat32chunk", Pyrophoric);

    memset(chunk, 0, sizeofSaveChunk(size64));
    chunk->type = old->type;
    chunk->contentsSize = size64;
    saveCat32Chunks++;
    return chunk;
}

