/*-----------------------------------------------------------------------------
    Name        : oracleUnivUpdate
    Description : univUpdate, then a 'T' record if the tick counter moved (the
                  GOG hook H1 does the same on univUpdate's exit). Used at every
                  univUpdate call site of universeUpdateTask, so univUpdate
                  itself stays as ported.
    Inputs      : phystimeelapsed - passed through
    Outputs     :
    Return      : univUpdate's result
----------------------------------------------------------------------------*/
bool32 oracleUnivUpdate(real32 phystimeelapsed)
{
    udword before = universe.univUpdateCounter;
    bool32 result;
    char text[HWO_EVENT_TEXT_MAX];

    // the deliberate perturbation (/oracleSelfTestPerturb <tick>): one extra RAN_Game draw before that tick, in the
    // self-test and in a mission run alike [M2-R4 rest-oracle: moved here from the self-test loop]
    if ((oracleSelfTestPerturbTick >= 1) && ((sdword)before + 1 == oracleSelfTestPerturbTick) &&
        (oracleInSelfTest || oracleMissionTicks > 0) && !oracleMissionDone)
    {
        (void)gamerand();
        oracleEmitEvent(HWO_EV_PERTURB, "one extra gamerand() before this tick");
    }

    result = univUpdate(phystimeelapsed);

    // CAT (M2-R5 dock): the scripted dock self-test rides on the mission run: its orders and checks happen here, after
    //      each universe tick (Dock.c catDockSelfTestTick)
    if (catDockSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catDockSelfTestTick();
    }
    // CAT (M2-R5 command-tactics): the command self-test the same way (CommandLayer.c catCommandSelfTestTick)
    if (catCommandSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catCommandSelfTestTick();
    }
    // CAT (M2-R5 render): the render self-test the same way (render.c catRenderSelfTestTick)
    if (catRenderSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catRenderSelfTestTick();
    }
    // CAT (M2-R5 hud): the HUD self-test the same way (InfoOverlay.c catHudSelfTestTick)
    if (catHudSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catHudSelfTestTick();
    }
    // CAT (M2-R6 mainrgn-popup): the popup / ui commands / game-stats self-test the same way (PopupMenu.c)
    if (catUiSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catUiSelfTestTick();
    }
    // CAT (M2-R6 startup-keys): the developer console's self-test the same way (Console.c catConsoleSelfTestTick)
    if (catConsoleSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catConsoleSelfTestTick();
    }
    // HWI-TEST (M2-R6 managers): the build self-test the same way (ConsMgr.c catBuildSelfTestTick)
    if (catBuildSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catBuildSelfTestTick();
    }
    // HWI-TEST (M2-R7 ai-orders-moves): the computer player's self-test the same way (AISelfTest.c catAiSelfTestTick)
    if (catAiSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catAiSelfTestTick();
    }
    // HWI-TEST (M2-R8 kas-runtime-mission01): the mission self-test the same way (MissionSelfTest.c)
    if ((catMissionSelfTestRequested() || catMissionSelfTestTutorialRequested()) && (universe.univUpdateCounter != before))
    {
        catMissionSelfTestTick();
    }
    // HWI-TEST (M2-R8 singleplayer-tutorial): the single-player save load's ticks (MissionSelfTest.c)
    if (catLoadGameSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catLoadGameSelfTestTick();
    }
    // HWI-TEST (skirmish-start): the skirmish self-test's judgement the same way (LevelLoad.c catSkirmishSelfTestTick)
    if (catSkirmishSelfTestRequested() && (universe.univUpdateCounter != before))
    {
        catSkirmishSelfTestTick();
    }

    // HWI-FEATURE(motion-interp) measurement: the motion / nis modes' scripted ships and NIS (MotionTest.c)
    if (catMotionTestRequested() && (universe.univUpdateCounter != before))     // HWI-FEATURE(motion-interp)
    {                                                                           // HWI-FEATURE(motion-interp)
        catMotionTestTick();                                                    // HWI-FEATURE(motion-interp)
    }                                                                           // HWI-FEATURE(motion-interp)

    if ((oracleFileName[0] != '\0' || oracleInSelfTest) && universe.univUpdateCounter != before)
    {
        oracleEmitTick();
    }
    // HWI-ORACLE (M2-R9 recorder-leftovers): the mode-B recording's start and stop, after the tick's record (the DLL's
    //      on_tick order)
    if (universe.univUpdateCounter != before)
    {
        oracleRecordTick();
    }
    // HWI-ORACLE (M2-R8 oracle-rung-physics): the per-ship dump's 'S' lines of this tick (/oracleShipDump)
    if (oracleShipDumpOn && (universe.univUpdateCounter != before))
    {
        oracleShipDumpTick();
    }
    // the mission run: a progress line every 256 ticks, then the stop at the requested tick (utyGameQuit only pushes
    // the exit event; the main loop quits normally, so the stream and the logs are complete)
    if ((oracleMissionTicks > 0) && !oracleMissionDone && (universe.univUpdateCounter != before))
    {
        if ((universe.univUpdateCounter % 256) == 0)
        {
            fprintf(stdout, "oracle: mission tick %u records=%u\n", (unsigned)universe.univUpdateCounter, (unsigned)oracleRecords);
            fflush(stdout);
        }
        if ((sdword)universe.univUpdateCounter >= oracleMissionTicks)
        {
            oracleMissionDone = TRUE;
            snprintf(text, sizeof(text), "ticks=%u records=%u ships=%u", (unsigned)universe.univUpdateCounter,
                     (unsigned)oracleRecords, (unsigned)universe.ShipList.num);
            oracleEmitEvent(HWO_EV_QUIT, text);
            fprintf(stdout, "oracle: mission run done %s file=%s\n", text, oracleFileName);
            // HWI-TEST (M2-R6 nis-fow-camera): the fog-of-war state of the run (stdout only, not in the stream): each
            //      player's grid pointer (cat_fowCreatePlayerGrids gives one to the local player, curPlayer, as the exe)
            //      and how often the stealth detection ran
            {
                udword index;
                fprintf(stdout, "oracle: mission fow players=%u curPlayer=%u", (unsigned)universe.numPlayers, (unsigned)curPlayer);
                for (index = 0; index < universe.numPlayers; index++)
                {
                    fprintf(stdout, " grid%u=%s", (unsigned)index, (universe.players[index].catFOWGrid != NULL) ? "set" : "NULL");
                }
                fprintf(stdout, " stealthUpdates=%u repairbots=%d droidUpdates=%u\n", (unsigned)catStealthDetectionUpdates,
                        (int)enableRepairbots, (unsigned)catDroidUpdates);
            }
            fflush(stdout);
            oracleClose();
            oracleFailed = TRUE;                    // the stream is complete: nothing may reopen (and truncate) it
            utyGameQuit(NULL, NULL);
        }
    }
    return result;
}

/*-----------------------------------------------------------------------------
    Name        : oracleEmitPacket
    Description : the 'P' record, at the end of netcheckShow (GOG hook H2): the
                  sync checksums exactly as computed and stored, and the sync
                  error counters after this packet's check.
    Inputs      : packet - the HWPacketHeader netcheckShow got; the values it computed
    Outputs     :
    Return      :
----------------------------------------------------------------------------*/
void oracleEmitPacket(void *packet, uword packetnum, uword randcheck, real32 univcheck, udword blobcheck)
{
    HwoPacket rec;
    uint8_t buf[HWO_RECPREFIX_SIZE + HWO_PACKET_PAYLOAD];

    if ((oracleFileName[0] == '\0' && !oracleInSelfTest) || !oracleOpen())
    {
        return;
    }
    memset(&rec, 0, sizeof(rec));
    rec.tick = (uint32_t)universe.univUpdateCounter;
    rec.packetnum = packetnum;
    rec.randcheck = randcheck;
    rec.univcheck = oracleFloatBits(univcheck);
    rec.blobcheck = blobcheck;
    rec.extra = catSyncExtra;                       // CAT (M2-R6 oracle-mode-a): the 4th sync field (0x00ab7658)
    if (oracleReplayRequested())
    {
        oracleReplayPacket();
    }
    rec.ncommands = ((HWPacketHeader *)packet)->numberOfCommands;
    rec.flags = HWO_PF_EXTRA;
#if SYNC_CHECK
    rec.randSyncErr = randSyncErr;
    rec.univSyncErr = univSyncErr;
    rec.blobSyncErr = blobSyncErr;
    rec.pktSyncErr = pktSyncErr;
    rec.randSyncErrFrame = randSyncErrFrame;
    rec.univSyncErrFrame = univSyncErrFrame;
    rec.blobSyncErrFrame = blobSyncErrFrame;
#endif
    oracleWrite(buf, hwoPackPacket(buf, &rec));
}

/*-----------------------------------------------------------------------------
    Name        : oracleEmitGameStart
    Description : at the end of gameStart (GOG hook H7): an 'E' record (new game
                  or the loaded file) and a 'T' record of the state right after
                  start/load, before the first tick (design 5.2 stage 1)
    Inputs      : loadfilename - gameStart's argument (NULL for a new game)
    Outputs     :
    Return      :
----------------------------------------------------------------------------*/
void oracleEmitGameStart(char *loadfilename)
{
    if (oracleFileName[0] == '\0' && !oracleInSelfTest)
    {
        return;
    }
    oracleEmitEvent(loadfilename != NULL ? HWO_EV_GAME_LOAD : HWO_EV_GAME_NEW, loadfilename != NULL ? loadfilename : "new");
    oracleEmitTick();
}

