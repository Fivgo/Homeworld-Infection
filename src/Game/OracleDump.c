/*-----------------------------------------------------------------------------
    Name        : oracleRunSelfTest
    Description : /oracleSelfTest <ticks>: the oracle's deterministic scripted
                  start. No recording exists yet (no HW1 data on the build
                  machine; the first GOG recording is the user's), and with
                  Cataclysm data hwi-engine cannot start a game before stage 2
                  (docs/m2-r2-oracle.md "selftest"). So, right after start-up,
                  this resets the universe and the RNG as gameStart does for a
                  new game, sets up two players with no ships, and runs the
                  lockstep branch of universeUpdateTask by hand: per sync packet
                  the captain's checksum copy (netcheckFillInChecksum), the
                  check (netcheckShow: univGetChecksum, statsGetStatChecksum,
                  one gamerand()), then two univUpdate ticks. Every tick, packet
                  and the start go to the .hwo stream exactly as in a game.
                  /oracleSelfTestPerturb <tick> draws one extra gamerand() just
                  before <tick>, for testing the comparison tool.
    Inputs      :
    Outputs     : the .hwo stream; a log line "oracle: self-test done ..."
    Return      :
----------------------------------------------------------------------------*/
void oracleRunSelfTest(void)
{
    HWPacketHeader packet;
    udword packetnum = 0;
    sdword i, k;
    Player *player;
    char text[HWO_EVENT_TEXT_MAX];

    oracleInSelfTest = TRUE;
    if (!oracleOpen())
    {
        return;
    }

    // the new-game resets of gameStart (loadfilename == NULL) for a non-single-player game, and a fresh sync-checksum
    // ring. CAT: gameStart 0x005a9290 calls cat_ranResetGameStreams (streams 1..26), not ranStartup; stream 0 keeps the
    // state ranStartup gave it at start-up (its wall-clock second is 0 here: oracleSetVirtualClock)
    univupdateReset();
    cat_ranResetGameStreams();
    netcheckReset();

    // two players, no ships: gameStart's per-player set-up for a new non-single-player game
    universe.numPlayers = ORACLE_SELFTEST_PLAYERS;
    tpGameCreated.numPlayers = ORACLE_SELFTEST_PLAYERS;
    tpGameCreated.numComputers = 0;
    for (i = 0; i < ORACLE_SELFTEST_PLAYERS; i++)
    {
        player = &universe.players[i];
        player->PlayerMothership = NULL;
        player->resourceUnits = ORACLE_SELFTEST_START_RU;
        player->playerState = PLAYER_ALIVE;
        player->playerIndex = (uword)i;
        player->aiPlayer = NULL;
    }
    universe.curPlayerIndex = 0;
    universe.curPlayerPtr = &universe.players[0];

    snprintf(text, sizeof(text), "ticks=%d players=%d perturb=%d rate=%d", (int)oracleSelfTestTicks,
             ORACLE_SELFTEST_PLAYERS, (int)oracleSelfTestPerturbTick, (int)UNIVERSE_UPDATE_RATE);
    oracleEmitEvent(HWO_EV_SELFTEST_START, text);
    oracleEmitTick();                               // tick 0, as hook H7 writes after gameStart

    while ((sdword)universe.univUpdateCounter < oracleSelfTestTicks && !oracleFailed)
    {
        // one sync packet: the lockstep branch of universeUpdateTask (clWaitSyncPacket -> netcheckShow, then 2 ticks)
        memset(&packet, 0, sizeof(packet));
        packet.frame = packetnum++;
#if SYNC_CHECK
        netcheckFillInChecksum(&packet);            // the captain's copy of its last checksum (captainServerTask)
#endif
        netcheckShow(&packet);

        for (k = 0; k < 2 && (sdword)universe.univUpdateCounter < oracleSelfTestTicks; k++)
        {
            ORACLE_UNIV_UPDATE(UNIVERSE_UPDATE_PERIOD);     // the /oracleSelfTestPerturb draw happens in oracleUnivUpdate
        }
    }

#if SYNC_CHECK
    snprintf(text, sizeof(text), "ticks=%u packets=%u randSyncErr=%u univSyncErr=%u blobSyncErr=%u",
             (unsigned)universe.univUpdateCounter, (unsigned)packetnum, (unsigned)randSyncErr,
             (unsigned)univSyncErr, (unsigned)blobSyncErr);
#else
    snprintf(text, sizeof(text), "ticks=%u packets=%u", (unsigned)universe.univUpdateCounter, (unsigned)packetnum);
#endif
    oracleEmitEvent(HWO_EV_SELFTEST_END, text);
    fprintf(stdout, "oracle: self-test done %s records=%u file=%s\n", text, (unsigned)oracleRecords, oracleFileName);
    fflush(stdout);
    oracleClose();
    oracleFailed = TRUE;                            // the stream is complete: nothing may reopen (and truncate) it
    oracleInSelfTest = FALSE;
}

