// the MXCSR control bits only (DAZ, exception masks, rounding control, FZ). [audit: bits 0-5 are the sticky exception
// status flags (IE DE ZE OE UE PE); the first self-test streams recorded 0x1FA5 = control 0x1F80 + IE|ZE|PE. Status
// flags can be set by code outside the simulation (rendering) at a tick that depends on frame timing, so they would
// make fpcw differ between two otherwise identical runs; the GOG side's fnstcw reads the x87 control word only.]
static uint16_t oracleFpControl(void)
{
#ifdef ORACLE_HAVE_MXCSR
    return (uint16_t)(_mm_getcsr() & 0xFFC0u);
#else
    return 0;
#endif
}

static uint32_t oracleFloatBits(real32 f)
{
    uint32_t u;
    memcpy(&u, &f, sizeof(u));
    return u;
}

static void oracleClose(void)
{
    if (oracleFile != NULL)
    {
        fclose(oracleFile);
        oracleFile = NULL;
    }
    if (oracleShipDumpFile != NULL)
    {
        fclose(oracleShipDumpFile);
        oracleShipDumpFile = NULL;
        oracleShipDumpFailed = TRUE;                // complete: nothing may reopen (and truncate) it
    }
}

static bool32 oracleWrite(const uint8_t *buf, size_t size)
{
    if (oracleFile == NULL)
    {
        return FALSE;
    }
    if (fwrite(buf, 1, size, oracleFile) != size || fflush(oracleFile) != 0)
    {
        fprintf(stderr, "oracle: write to '%s' failed; oracle stream disabled\n", oracleFileName);
        oracleClose();
        oracleFailed = TRUE;
        return FALSE;
    }
    oracleRecords++;
    return TRUE;
}

// opens the stream on first use and writes the 64-byte header; FALSE if the oracle is off
static bool32 oracleOpen(void)
{
    HwoHeader header;
    uint8_t buf[HWO_HEADER_SIZE];
    const char *base;
    size_t n;

    if (oracleFile != NULL)
    {
        return TRUE;
    }
    if (oracleFailed)
    {
        return FALSE;
    }
    if (oracleFileName[0] == '\0')
    {
        if (!oracleInSelfTest)
        {
            return FALSE;
        }
        strcpy(oracleFileName, ORACLE_SELFTEST_DEFAULT_FILE);
    }

    oracleFile = fopen(oracleFileName, "wb");
    if (oracleFile == NULL)
    {
        fprintf(stderr, "oracle: cannot create '%s'; oracle stream disabled\n", oracleFileName);
        oracleFailed = TRUE;
        return FALSE;
    }
    atexit(oracleClose);

    memset(&header, 0, sizeof(header));
    header.version = HWO_VERSION;
    header.producer = HWO_PRODUCER_HWI;
    if (oracleInSelfTest)
    {
        header.mode = HWO_MODE_SELFTEST;
    }
    else if (playPackets)
    {
        header.mode = HWO_MODE_PLAYBACK;
    }
    else if (recordPackets)
    {
        header.mode = HWO_MODE_RECORD;
    }
    else
    {
        header.mode = HWO_MODE_OBSERVE;
    }
    // realtimeelapsed is tick-derived in oracle runs (univRealTimeVirtual) and the stream-0 wall-clock seed is 0
    // (ranVirtualWallClock), like the GOG side's clock=virtual; there is no stream-0 split (rng0) on this side
    header.options = HWO_OPT_CLOCK_VIRTUAL;
    if ((oracleInSelfTest || oracleMissionTicks > 0) && oracleSelfTestPerturbTick >= 1)
    {
        header.options |= HWO_OPT_PERTURBED;
    }
    header.ident1 = (uint32_t)HWI_GIT_HASH;
    header.ident2 = hwoFnv32Str(HWI_BUILD_FLAGS);
    header.fpcw = oracleFpControl();
    header.ticks_per_second = (uint16_t)UNIVERSE_UPDATE_RATE;
    if (oracleInSelfTest)
    {
        if (oracleSelfTestPerturbTick >= 1)
        {
            snprintf(header.tag, sizeof(header.tag), "selftest-perturb@%d", (int)oracleSelfTestPerturbTick);
        }
        else
        {
            snprintf(header.tag, sizeof(header.tag), "selftest");
        }
    }
    else
    {
        base = strrchr(oracleFileName, '/');
        base = (base != NULL) ? base + 1 : oracleFileName;
        n = strlen(base);
        if (n > sizeof(header.tag) - 1)
        {
            n = sizeof(header.tag) - 1;
        }
        memcpy(header.tag, base, n);
    }

    hwoPackHeader(buf, &header);
    if (!oracleWrite(buf, HWO_HEADER_SIZE))
    {
        return FALSE;
    }
    fprintf(stdout, "oracle: writing '%s' (%u ticks/s, build %08x, flags %08x)\n", oracleFileName,
            (unsigned)header.ticks_per_second, (unsigned)header.ident1, (unsigned)header.ident2);
    return TRUE;
}

static void oracleEmitEvent(uint16_t code, const char *text)
{
    uint8_t buf[HWO_RECPREFIX_SIZE + HWO_EVENT_FIXED + HWO_EVENT_TEXT_MAX];

    if (!oracleOpen())
    {
        return;
    }
    oracleWrite(buf, hwoPackEvent(buf, (uint32_t)universe.univUpdateCounter, code, text));
}

static uint64_t oracleHashPos(uint64_t h, const vector *v)
{
    h = hwoFnvU32(h, oracleFloatBits(v->x));
    h = hwoFnvU32(h, oracleFloatBits(v->y));
    return hwoFnvU32(h, oracleFloatBits(v->z));
}

// live objects of a list of SpaceObj-derived structs: count and FNV-1a-64 of their positions in list order
static uint16_t oracleHashList(LinkedList *list, uint64_t *hash)
{
    Node *node;
    SpaceObj *obj;
    uint16_t n = 0;
    uint64_t h = HWO_FNV64_INIT;

    for (node = list->head; node != NULL; node = node->next)
    {
        obj = (SpaceObj *)listGetStructOfNode(node);
        if (obj->header.flags & SOF_Dead)
        {
            continue;
        }
        h = oracleHashPos(h, &obj->posinfo.position);
        n++;
    }
    *hash = h;
    return n;
}

static void oracleFillTick(HwoTick *t)
{
    FILE *savedNetlog;
    sdword numShips = 0;
    real32 univcheck;
    udword statcheck;
    uint32_t crc = 0;
    sdword i;
    Node *node;
    Ship *ship;
    const matrix *m;
    uint16_t id;
    uint16_t order, attributes;

    memset(t, 0, sizeof(*t));
    t->tick = (uint32_t)universe.univUpdateCounter;
    t->dt = oracleFloatBits(universe.phystimeelapsed);
    t->total = oracleFloatBits(universe.totaltimeelapsed);
    t->real = oracleFloatBits(universe.realtimeelapsed);    // CAT: realtimeelapsed is ported (M2-R3)
    t->fpcw = oracleFpControl();
    t->valid = HWO_TV_REAL | HWO_TV_SHIPMISC | HWO_TV_HEALTH | HWO_TV_LISTS | HWO_TV_PLAYERS | HWO_TV_CHECKSUMS;

    // the game's own checksums, computed by the game's own functions with the net log muted (they write to it)
    savedNetlog = netlogfile;
    netlogfile = NULL;
    univcheck = univGetChecksum(&numShips);
    statcheck = statsGetStatChecksum();
    netlogfile = savedNetlog;
    t->univcheck = oracleFloatBits(univcheck);
    t->nships = (uint16_t)numShips;
    t->statcheck = (uint32_t)statcheck;

    // RNG state, read and never drawn
    for (i = 0; i < RANDOM_NUMBER_STREAMS; i++)
    {
        crc = hwoCrc32Update(crc, ranStream[i].x);
        crc = hwoCrc32Update(crc, ranStream[i].y);
        crc = hwoCrc32Update(crc, ranStream[i].z);
        crc = hwoCrc32Update(crc, ranStream[i].c);
        crc = hwoCrc32Update(crc, ranStream[i].n);
    }
    t->rng_streams = RANDOM_NUMBER_STREAMS;
    t->rng_all = crc;
#define ORACLE_COPY_STREAM(dst, s) \
    (dst).x = ranStream[s].x; (dst).y = ranStream[s].y; (dst).z = ranStream[s].z; \
    (dst).c = ranStream[s].c; (dst).n = ranStream[s].n
    ORACLE_COPY_STREAM(t->rng10, RANDOM_GAME);
    ORACLE_COPY_STREAM(t->rng6, RANDOM_AI_PLAYER);
    ORACLE_COPY_STREAM(t->rng0, RANDOM_STREAM_0);   // CAT: stream 0 by index (Randy.h renumbering)
#undef ORACLE_COPY_STREAM

    // live ships in ShipList order (list order is part of determinism, so it is hashed as is)
    t->ships_pos = t->ships_vel = t->ships_rot = t->ships_misc = t->ships_health = HWO_FNV64_INIT;
    for (node = universe.ShipList.head; node != NULL; node = node->next)
    {
        ship = (Ship *)listGetStructOfNode(node);
        if (ship->header.flags & SOF_Dead)
        {
            continue;
        }
        id = (uint16_t)ship->shipID.shipNumber;

        t->ships_pos = oracleHashPos(hwoFnvU16(t->ships_pos, id), &ship->obj.posinfo.position);
        t->ships_vel = oracleHashPos(hwoFnvU16(t->ships_vel, id), &ship->obj.posinfo.velocity);

        m = &ship->rotatable.rotinfo.coordsys;
        t->ships_rot = hwoFnvU16(t->ships_rot, id);
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m11));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m21));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m31));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m12));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m22));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m32));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m13));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m23));
        t->ships_rot = hwoFnvU32(t->ships_rot, oracleFloatBits(m->m33));

        if (ship->command != NULL)
        {
            order = (uint16_t)ship->command->ordertype.order;
            attributes = (uint16_t)ship->command->ordertype.attributes;
        }
        else
        {
            order = attributes = 0xFFFFu;
        }
        t->ships_misc = hwoFnvU16(t->ships_misc, id);
        t->ships_misc = hwoFnvU32(t->ships_misc, (uint32_t)ship->shiptype);
        t->ships_misc = hwoFnvU32(t->ships_misc, (uint32_t)ship->shiprace);
        t->ships_misc = hwoFnvU16(t->ships_misc, (ship->playerowner != NULL) ? (uint16_t)ship->playerowner->playerIndex : 0xFFFFu);
        t->ships_misc = hwoFnvU16(t->ships_misc, order);
        t->ships_misc = hwoFnvU16(t->ships_misc, attributes);

        t->ships_health = hwoFnvU32(hwoFnvU16(t->ships_health, id), oracleFloatBits(ship->targetable.health));


        t->ships_n++;
    }

    // the objects the engine's own checksum ignores (docs/m2-checksum-oracle.md 2.2)
    t->missiles_n = oracleHashList(&universe.MissileList, &t->missiles_h);
    t->bullets_n = oracleHashList(&universe.BulletList, &t->bullets_h);
    t->derelicts_n = oracleHashList(&universe.DerelictList, &t->derelicts_h);
    t->resources_n = oracleHashList(&universe.ResourceList, &t->resources_h);

    for (i = 0; i < HWO_MAX_PLAYERS; i++)
    {
        t->player_ru[i] = (uint32_t)universe.players[i].resourceUnits;
        t->player_ships[i] = (uint32_t)universe.players[i].totalships;
    }
}

/*-----------------------------------------------------------------------------
    HWI-ORACLE (M2-R8 oracle-rung-physics): the per-ship / per-packet dump (/oracleShipDump). Every float is written
    as its bits and its value, so a line gives the exact words the stream hashes (ships_pos, ships_vel, ships_rot,
    ships_health) and tools/oracle/hwo_invert.py can rebuild a tick's hashes from an "all" dump.
      S <tick> <ship> <type> <owner> <order> <attributes> <aistate> <flags> pos=<3> vel=<3> rotspeed=<3>
        coordsys=<9: m11 m21 m31 m12 m22 m32 m13 m23 m33> health=<1> (<x> = hex bits:value)
      C <tick> <frame> <index> <type> <from> <bytes>: one command of a sync packet before clProcessSyncPacket runs it
      A <tick> <ship> force|rot <dir> <value>: a force / torque given to the ship (physApplyForceToObj / physApplyRotToObj)
      F <tick> <ship> force=<3> torque=<3>: the sums the ship's physics update integrates (physUpdateObjPosVelShip)
      V <tick> <ship> target|repulse|desired v=<3>: the flight's vectors (aishipFlyToPointAvoidingObjsFunc)
      R <tick> <index> <objtype> pos=<3> vel=<3>: with "all", every live resource in ResourceList order
----------------------------------------------------------------------------*/
static bool32 oracleShipDumpOpen(void)
{
    char path[1100];
    const char *slash;
    size_t dirlen = 0;

    if (oracleShipDumpFile != NULL)
    {
        return TRUE;
    }
    if (!oracleShipDumpOn || oracleShipDumpFailed)
    {
        return FALSE;
    }
    slash = strrchr(oracleFileName, ORACLE_PATH_SEP);
    if (slash != NULL)
    {
        dirlen = (size_t)(slash - oracleFileName) + 1;
    }
    snprintf(path, sizeof(path), "%.*sshipdump.txt", (int)dirlen, oracleFileName);
    oracleShipDumpFile = fopen(path, "w");
    if (oracleShipDumpFile == NULL)
    {
        fprintf(stdout, "oracle: shipdump cannot open '%s'\n", path);
        oracleShipDumpFailed = TRUE;
        return FALSE;
    }
    fprintf(stdout, "oracle: shipdump file=%s ships=%s from=%u to=%u\n", path, oracleShipDumpAll ? "all" : "list",
            (unsigned)oracleShipDumpFrom, (unsigned)oracleShipDumpTo);
    fflush(stdout);
    return TRUE;
}

static bool32 oracleShipDumpWanted(udword tick, udword shipnumber)
{
    udword i;

    if (!oracleShipDumpOn || (tick < oracleShipDumpFrom) || (tick > oracleShipDumpTo))
    {
        return FALSE;
    }
    if (oracleShipDumpAll)
    {
        return TRUE;
    }
    for (i = 0; i < oracleShipDumpNum; i++)
    {
        if (oracleShipDumpIds[i] == shipnumber)
        {
            return TRUE;
        }
    }
    return FALSE;
}

static void oracleShipDumpFloats(const char *name, const real32 *f, udword n)
{
    udword i;

    fprintf(oracleShipDumpFile, " %s=", name);
    for (i = 0; i < n; i++)
    {
        fprintf(oracleShipDumpFile, "%s%08x:%.9g", (i == 0) ? "" : ",", (unsigned)oracleFloatBits(f[i]), (double)f[i]);
    }
}

// a target as the dump names it: a ship's number, or "o<objtype>" for any other object, or "-" for none
static void oracleShipDumpTarget(const SpaceObjRotImpTarg *target)
{
    if (target == NULL)
    {
        fputc('-', oracleShipDumpFile);
    }
    else if (target->header.objtype == OBJ_ShipType)
    {
        fprintf(oracleShipDumpFile, "%u", (unsigned)((const Ship *)target)->shipID.shipNumber);
    }
    else
    {
        fprintf(oracleShipDumpFile, "o%d", (int)target->header.objtype);
    }
}

// HWI-ORACLE (M2-R10 oracle-rung-physics): the 'T' and 'G' lines of one dumped ship (read only)
static void oracleShipDumpAttack(udword tick, Ship *ship)
{
    sdword i;

    fprintf(oracleShipDumpFile, "T %u %u state=%u target=", (unsigned)tick, (unsigned)ship->shipID.shipNumber,
            (unsigned)ship->aistateattack);
    oracleShipDumpTarget(ship->attackvars.attacktarget);
    fputs(" cmd=", oracleShipDumpFile);
    if ((ship->command != NULL) && (ship->command->attack != NULL))
    {
        for (i = 0; i < ship->command->attack->numTargets; i++)
        {
            if (i > 0)
            {
                fputc(',', oracleShipDumpFile);
            }
            oracleShipDumpTarget(ship->command->attack->TargetPtr[i]);
        }
    }
    else
    {
        fputc('-', oracleShipDumpFile);
    }
    if (ship->attackvars.multipleAttackTargets != NULL)
    {
        fputs(" multi=", oracleShipDumpFile);
        for (i = 0; i < ship->attackvars.multipleAttackTargets->numAttackTargets; i++)
        {
            if (i > 0)
            {
                fputc(',', oracleShipDumpFile);
            }
            oracleShipDumpTarget(ship->attackvars.multipleAttackTargets->TargetPtr[i]);
        }
    }
    fprintf(oracleShipDumpFile, " madGun=%d\n", (int)ship->madGunStatus);
    if (ship->gunInfo != NULL)
    {
        for (i = 0; i < ship->gunInfo->numGuns; i++)
        {
            Gun *gun = &ship->gunInfo->guns[i];

            fprintf(oracleShipDumpFile, "G %u %u %d type=%d burst=%u", (unsigned)tick,
                    (unsigned)ship->shipID.shipNumber, (int)i, (int)gun->gunstatic->guntype, (unsigned)gun->burstState);
            oracleShipDumpFloats("last", &gun->lasttimefired, 1);
            oracleShipDumpFloats("heading", &gun->gunheading.x, 3);
            fputc('\n', oracleShipDumpFile);
        }
    }
}

static void oracleShipDumpTick(void)
{
    Node *node;
    Ship *ship;
    const matrix *m;
    real32 cs[9];
    udword tick = universe.univUpdateCounter;

    if (!oracleShipDumpOn || (tick < oracleShipDumpFrom) || (tick > oracleShipDumpTo) || !oracleShipDumpOpen())
    {
        return;
    }
    for (node = universe.ShipList.head; node != NULL; node = node->next)
    {
        ship = (Ship *)listGetStructOfNode(node);
        if ((ship->header.flags & SOF_Dead) || !oracleShipDumpWanted(tick, (udword)ship->shipID.shipNumber))
        {
            continue;
        }
        m = &ship->rotatable.rotinfo.coordsys;
        cs[0] = m->m11; cs[1] = m->m21; cs[2] = m->m31;
        cs[3] = m->m12; cs[4] = m->m22; cs[5] = m->m32;
        cs[6] = m->m13; cs[7] = m->m23; cs[8] = m->m33;
        fprintf(oracleShipDumpFile, "S %u %u %s %d %d %d %u %08x", (unsigned)tick, (unsigned)ship->shipID.shipNumber,
                ShipTypeToStr(ship->shiptype), (ship->playerowner != NULL) ? (int)ship->playerowner->playerIndex : -1,
                (ship->command != NULL) ? (int)ship->command->ordertype.order : -1,
                (ship->command != NULL) ? (int)ship->command->ordertype.attributes : -1,
                (unsigned)ship->shipOrDerelict.aistate, (unsigned)ship->header.flags);
        oracleShipDumpFloats("pos", &ship->obj.posinfo.position.x, 3);
        oracleShipDumpFloats("vel", &ship->obj.posinfo.velocity.x, 3);
        oracleShipDumpFloats("rotspeed", &ship->rotatable.rotinfo.rotspeed.x, 3);
        oracleShipDumpFloats("coordsys", cs, 9);
        oracleShipDumpFloats("health", &ship->targetable.health, 1);
        fputc('\n', oracleShipDumpFile);
        // M2-R10 oracle-rung-physics: one 'T' line per dumped ship (its attack state: aistateattack, the attack
        // target, the command's attack targets and, for a ship with multiple targets, each gun's) and one 'G' line
        // per gun (its last fire time, burst state and heading in ship space)
        oracleShipDumpAttack(tick, ship);
    }
    // with "all" (M2-R9 oracle-rung-physics): one 'B' line per live bullet in BulletList order (the 'bullets' hash's
    // order: positions only): the firing ship, its target and the bullet's position and velocity
    if (oracleShipDumpAll)
    {
        Bullet *bullet;
        udword bindex = 0;

        for (node = universe.BulletList.head; node != NULL; node = node->next)
        {
            bullet = (Bullet *)listGetStructOfNode(node);
            if (bullet->header.flags & SOF_Dead)
            {
                continue;
            }
            fprintf(oracleShipDumpFile, "B %u %u owner=%d target=%d", (unsigned)tick, (unsigned)bindex,
                    (bullet->owner != NULL) ? (int)bullet->owner->shipID.shipNumber : -1,
                    ((bullet->target != NULL) && (bullet->target->header.objtype == OBJ_ShipType)) ?
                        (int)((Ship *)bullet->target)->shipID.shipNumber : -1);
            oracleShipDumpFloats("pos", &bullet->obj.posinfo.position.x, 3);
            oracleShipDumpFloats("vel", &bullet->obj.posinfo.velocity.x, 3);
            fputc('\n', oracleShipDumpFile);
            bindex++;
        }
    }
    // with "all": one 'R' line per live resource in ResourceList order (the 'resources' hash's order: positions only)
    if (oracleShipDumpAll)
    {
        SpaceObj *obj;
        udword index = 0;

        for (node = universe.ResourceList.head; node != NULL; node = node->next)
        {
            obj = (SpaceObj *)listGetStructOfNode(node);
            if (obj->header.flags & SOF_Dead)
            {
                continue;
            }
            fprintf(oracleShipDumpFile, "R %u %u %d", (unsigned)tick, (unsigned)index, (int)obj->header.objtype);
            oracleShipDumpFloats("pos", &obj->posinfo.position.x, 3);
            oracleShipDumpFloats("vel", &obj->posinfo.velocity.x, 3);
            fputc('\n', oracleShipDumpFile);
            index++;
        }
    }
}

// 'A' / 'F' lines: the forces and torques a dumped ship is given during a tick (physApplyForceToObj /
// physApplyRotToObj, kind "force" / "rot", the direction and the value's bits) and their sums as the ship's physics
// update integrates them (physUpdateObjPosVelShip); <tick> is univUpdateCounter while the update runs
void oracleShipDumpApply(void *shipobj, const char *kind, udword dir, real32 value)
{
    SpaceObj *obj = (SpaceObj *)shipobj;
    udword tick = universe.univUpdateCounter;

    if (!oracleShipDumpOn || (obj->header.objtype != OBJ_ShipType) ||
        !oracleShipDumpWanted(tick, (udword)((Ship *)obj)->shipID.shipNumber) || !oracleShipDumpOpen())
    {
        return;
    }
    fprintf(oracleShipDumpFile, "A %u %u %s %u %08x:%.9g\n", (unsigned)tick, (unsigned)((Ship *)obj)->shipID.shipNumber,
            kind, (unsigned)dir, (unsigned)oracleFloatBits(value), (double)value);
}

// 'V' lines: the flight's vectors of a dumped ship (aishipFlyToPointAvoidingObjsFunc: "target" the capped target
// velocity, "repulse" each avoidance term added, "desired" the velocity handed to the guidance)
void oracleShipDumpVector(void *shipobj, const char *kind, const vector *v)
{
    Ship *ship = (Ship *)shipobj;
    udword tick = universe.univUpdateCounter;

    if (!oracleShipDumpOn || !oracleShipDumpWanted(tick, (udword)ship->shipID.shipNumber) || !oracleShipDumpOpen())
    {
        return;
    }
    fprintf(oracleShipDumpFile, "V %u %u %s", (unsigned)tick, (unsigned)ship->shipID.shipNumber, kind);
    oracleShipDumpFloats("v", &v->x, 3);
    fputc('\n', oracleShipDumpFile);
}

// 'V <tick> <ship> fly' lines (M2-R9 oracle-rung-physics): the inputs of a dumped ship's flight as
// aishipFlyToPointAvoidingObjsFunc receives them (the destination or none, the AISHIP_ flags, limitvel and the velocity
// it flies with or none), written when its STATE_START_FLYING computes the target velocity
void oracleShipDumpFly(void *shipobj, const vector *destination, udword flags, real32 limitvel, const vector *withVel)
{
    Ship *ship = (Ship *)shipobj;
    udword tick = universe.univUpdateCounter;
    static const real32 none[3] = { 0.0f, 0.0f, 0.0f };

    if (!oracleShipDumpOn || !oracleShipDumpWanted(tick, (udword)ship->shipID.shipNumber) || !oracleShipDumpOpen())
    {
        return;
    }
    fprintf(oracleShipDumpFile, "V %u %u fly flags=%08x", (unsigned)tick, (unsigned)ship->shipID.shipNumber, (unsigned)flags);
    oracleShipDumpFloats(destination != NULL ? "dest" : "nodest", destination != NULL ? &destination->x : none, 3);
    oracleShipDumpFloats("limitvel", &limitvel, 1);
    oracleShipDumpFloats(withVel != NULL ? "withvel" : "nowithvel", withVel != NULL ? &withVel->x : none, 3);
    fputc('\n', oracleShipDumpFile);
}

// 'O' lines (M2-R9 oracle-rung-physics): each object a dumped ship's flight avoids (aishipFlyToPointAvoidingObjsFunc,
// after the distance test): the object's type (objtype, the ship number or -1, the ship type or -1), its collision
// position and coordinate system (hash order), the distance as the float the exe stores, the normal, and the three
// doubles of the collision distance (the avoided object's size, the ship's size, distance - their sum before the 20
// floor) as raw 64-bit words
static void oracleShipDumpDouble(const char *name, double d)
{
    uint64_t bits;

    memcpy(&bits, &d, sizeof(bits));
    fprintf(oracleShipDumpFile, " %s=%016llx:%.17g", name, (unsigned long long)bits, d);
}

void oracleShipDumpAvoid(void *shipobj, void *avoidobj, real32 dist, const vector *norm, double avoidsize, double shipsize,
                         double dtc)
{
    Ship *ship = (Ship *)shipobj;
    SpaceObjRotImp *obj = (SpaceObjRotImp *)avoidobj;
    udword tick = universe.univUpdateCounter;
    const matrix *m = &obj->rotatable.rotinfo.coordsys;
    real32 cs[9];

    if (!oracleShipDumpOn || !oracleShipDumpWanted(tick, (udword)ship->shipID.shipNumber) || !oracleShipDumpOpen())
    {
        return;
    }
    cs[0] = m->m11; cs[1] = m->m21; cs[2] = m->m31;
    cs[3] = m->m12; cs[4] = m->m22; cs[5] = m->m32;
    cs[6] = m->m13; cs[7] = m->m23; cs[8] = m->m33;
    fprintf(oracleShipDumpFile, "O %u %u %d %d %d", (unsigned)tick, (unsigned)ship->shipID.shipNumber,
            (int)((SpaceObj *)obj)->header.objtype,
            (((SpaceObj *)obj)->header.objtype == OBJ_ShipType) ? (int)((Ship *)obj)->shipID.shipNumber : -1,
            (((SpaceObj *)obj)->header.objtype == OBJ_ShipType) ? (int)((Ship *)obj)->shiptype : -1);
    oracleShipDumpFloats("collpos", &obj->collInfo.collPosition.x, 3);
    oracleShipDumpFloats("coordsys", cs, 9);
    oracleShipDumpFloats("dist", &dist, 1);
    oracleShipDumpFloats("norm", &norm->x, 3);
    oracleShipDumpDouble("avoidsize", avoidsize);
    oracleShipDumpDouble("shipsize", shipsize);
    oracleShipDumpDouble("dtc", dtc);
    fputc('\n', oracleShipDumpFile);
}

void oracleShipDumpPhys(void *shipobj)
{
    Ship *ship = (Ship *)shipobj;
    udword tick = universe.univUpdateCounter;

    if (!oracleShipDumpOn || !oracleShipDumpWanted(tick, (udword)ship->shipID.shipNumber) || !oracleShipDumpOpen())
    {
        return;
    }
    fprintf(oracleShipDumpFile, "F %u %u", (unsigned)tick, (unsigned)ship->shipID.shipNumber);
    oracleShipDumpFloats("force", &ship->obj.posinfo.force.x, 3);
    oracleShipDumpFloats("torque", &ship->rotatable.rotinfo.torque.x, 3);
    fputc('\n', oracleShipDumpFile);
}

void oracleShipDumpCommand(udword frame, udword index, udword type, udword from, const ubyte *body, udword size)
{
    udword i;
    udword tick = universe.univUpdateCounter;

    if (!oracleShipDumpOn || (tick + 1 < oracleShipDumpFrom) || (tick > oracleShipDumpTo) || !oracleShipDumpOpen())
    {
        return;
    }
    fprintf(oracleShipDumpFile, "C %u %u %u %u %u ", (unsigned)tick, (unsigned)frame, (unsigned)index, (unsigned)type,
            (unsigned)from);
    for (i = 0; i < size; i++)
    {
        fprintf(oracleShipDumpFile, "%02x", (unsigned)body[i]);
    }
    fputc('\n', oracleShipDumpFile);
}

static void oracleEmitTick(void)
{
    HwoTick tick;
    uint8_t buf[HWO_RECORD_MAX];

    if (!oracleOpen())
    {
        return;
    }
    oracleFillTick(&tick);
    oracleWrite(buf, hwoPackTick(buf, &tick));
}

