#!/usr/bin/env python3
"""Generate Cataclysm's string-id enum (src/Game/StringsOnly.h) and the LanguageStrings table of
src/Game/StringSupport.c from cataclysm.exe (M2-R3, docs/m2-r3-closeout-headers.md "strings").

Usage: tools/m2_strings_gen.py --exe cataclysm.exe [--hw1 src/reference/hw1-ad1bb82/Game/StringsOnly.h] [--check]

The exe's LanguageStrings (0x00898148) is a table of 1,705 scriptEntry rows {char *name; setVarCB; void *dataPtr}
ending with a NULL row at 0x0089d134; every callback is strSetStringCB (0x00528800) and every dataPtr is
&MessageStrings[id] (MessageStrings 0x00bb3620), so dataPtr gives the enum value of each name. strLoadLanguage
(0x005285f0) clears 0x6A9 = 1,705 MessageStrings. The enum is written in id order and the table in the exe's row
order (rows 564/565 point at ids 565/564; strNameToEnum 0x005288f0 returns the ROW index, as HW1's does).

HW1 names that Cataclysm dropped (from the HW1 enum, Relic ad1bb82 = GoK's) follow NumStrings as dormant ids, so
unported HW1 code compiles and reads "*NO_STRING*" (strLoadLanguage fills the whole array, StringSupport.c).

Reads the exe only; writes the two source files (or, with --check, only compares them and exits 1 on a difference).
"""
import argparse
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE, NROWS, CB, MSG = 0x00898148, 1705, 0x00528800, 0x00bb3620


def pe(path):
    d = open(path, "rb").read()
    o = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, o + 6)[0]
    optsz = struct.unpack_from("<H", d, o + 20)[0]
    base = struct.unpack_from("<I", d, o + 24 + 28)[0]
    secs = []
    for i in range(nsec):
        s = o + 24 + optsz + 40 * i
        vsize, va, rsize, roff = struct.unpack_from("<IIII", d, s + 8)
        secs.append((base + va, rsize, roff))

    def rd(a, n):
        for va, rs, ro in secs:
            if va <= a and a + n <= va + rs:
                return d[ro + a - va: ro + a - va + n]
        raise ValueError("address 0x%08x not in the file" % a)

    def cstr(a):
        out = b""
        while True:
            c = rd(a, 1)
            if c == b"\0":
                return out.decode("ascii")
            out += c
            a += 1
    return rd, cstr


def exe_rows(exe):
    rd, cstr = pe(exe)
    rows = []
    for i in range(NROWS + 1):
        name, cb, data = struct.unpack("<III", rd(TABLE + 12 * i, 12))
        if i == NROWS:
            assert name == cb == data == 0, "table does not end after %d rows" % NROWS
            break
        assert cb == CB, "row %d: callback 0x%08x" % (i, cb)
        assert (data - MSG) % 4 == 0 and 0 <= (data - MSG) // 4 < NROWS, "row %d: dataPtr 0x%08x" % (i, data)
        rows.append((cstr(name), (data - MSG) // 4))
    ids = sorted(r[1] for r in rows)
    assert ids == list(range(NROWS)), "dataPtrs are not a permutation of 0..%d" % (NROWS - 1)
    return rows


def hw1_names(path):
    text = open(path, encoding="latin-1").read()
    body = text.split("typedef enum")[1].split("NumStrings")[0]
    return re.findall(r"^\s*(str\w+)\s*,", body, re.M)


HEADER = """// =============================================================================
//  StringsOnly.h
// =============================================================================
//  Copyright Relic Entertainment, Inc. All rights reserved.
// =============================================================================

#ifndef ___STRINGSONLY_H
#define ___STRINGSONLY_H

// IMPORTANT:
// do not include Types.h, StatScript.h or any other game/Windows include files

// CAT: Cataclysm's %d string ids (HW1 590), generated by tools/m2_strings_gen.py from the exe's LanguageStrings
//      0x00898148 (each row's dataPtr is &MessageStrings[id], MessageStrings 0x00bb3620; strLoadLanguage 0x005285f0
//      clears 0x6A9 = %d strings). Ids 0..NumStrings-1 are the exe's; %d HW1 ids that Cataclysm dropped follow
//      NumStrings (dormant: no LanguageStrings row, so they read "*NO_STRING*"; never in the data).
typedef enum
{
"""

FOOTER = """
    // CAT: end of Cataclysm's ids; the HW1-only ids below are dormant
    NumStrings,
    strHW1LegacyFirst = NumStrings,
%s
    NumStringsWithLegacy
} strGamesMessages;

// CAT: string offsets. strShipOffset: ShipTypeToNiceStr 0x004d6c30 returns MessageStrings[type]; strClassOffset:
//      ShipClassToNiceStr 0x004d6b70 reads MessageStrings + 0x238 (id 142); strTechOffset: TechTypeToNiceString
//      0x004f2530 reads MessageStrings + 0x2D8 (id 182); strTechInfoOffsetR1/R2: rmTechInfoDraw/tmTechInfoDraw read
//      MessageStrings + 0x3F8 / + 0x49C (ids 254 / 295). strShipAbrevOffset: the 142 abbreviations follow the ship
//      names in type order. strTechHeadingOffset, strFormationOffset, strKeyCommandOffset keep their HW1 base names,
//      which exist in Cataclysm's table with HW1's order after them (their exe users were not located). strFirepower
//      has no Cataclysm string: strShipStatNameOffset is a dormant HW1 id.
#define strShipOffset         strsRecon
#define strClassOffset        strCLASS_Mothership
#define strTechOffset         strTECH_CLOAKING
#define strTechHeadingOffset  strWeaponHeading
#define strTechInfoOffsetR1   strR1TECH_CLOAKINGinfo
#define strTechInfoOffsetR2   strR2TECH_CLOAKINGinfo
#define strShipAbrevOffset    strAbrevsRecon
#define strFormationOffset    strDELTA_FORMATION
#define strShipStatNameOffset strFirepower
#define strKeyCommandOffset   strkbNEXT_FORMATION

#define strGetString(string) (MessageStrings[string])

extern char *MessageStrings[NumStringsWithLegacy];  // declared in StringSupport.c


#endif
"""

BEGIN = "    // CAT: BEGIN generated by tools/m2_strings_gen.py (the exe's LanguageStrings rows, in its order)\n"
END = "    // CAT: END generated by tools/m2_strings_gen.py\n"


def build(rows, hw1):
    by_id = sorted(rows, key=lambda r: r[1])
    cat = {n for n, _ in rows}
    legacy = [n for n in hw1 if n not in cat]
    h = HEADER % (NROWS, NROWS, len(legacy))
    h += "\n".join("    %s,%s" % (n, "" if i % 50 else "                  // %d" % i) for n, i in by_id)
    h += FOOTER % "\n".join("    %s," % n for n in legacy)
    t = BEGIN + "".join("    strEntry(%s),\n" % n for n, _ in rows) + END
    return h, t, legacy


def splice_table(src, table):
    if BEGIN in src:
        a = src.index(BEGIN)
        b = src.index(END) + len(END)
    else:
        a = src.index("scriptEntry LanguageStrings[] =\n{\n") + len("scriptEntry LanguageStrings[] =\n{\n")
        b = src.index("\n    END_SCRIPT_ENTRY", a) + 1
    return src[:a] + table + src[b:]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", required=True)
    ap.add_argument("--hw1", default=os.path.join(ROOT, "src/reference/hw1-ad1bb82/Game/StringsOnly.h"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = exe_rows(a.exe)
    hw1 = hw1_names(a.hw1)
    header, table, legacy = build(rows, hw1)
    hpath = os.path.join(ROOT, "src/Game/StringsOnly.h")
    cpath = os.path.join(ROOT, "src/Game/StringSupport.c")
    csrc = open(cpath, encoding="latin-1").read()
    cnew = splice_table(csrc, table)
    swapped = [(i, n, v) for i, (n, v) in enumerate(rows) if i != v]
    print("exe rows %d, ids 0..%d; rows whose id differs from the row index: %s" % (
        len(rows), len(rows) - 1, ", ".join("row %d %s -> id %d" % s for s in swapped) or "none"))
    print("HW1 names %d: %d also in Cataclysm, %d dormant HW1-only ids" % (len(hw1), len(hw1) - len(legacy), len(legacy)))
    if a.check:
        same = open(hpath, encoding="latin-1").read() == header and csrc == cnew
        print("check:", "up to date" if same else "DIFFERS")
        sys.exit(0 if same else 1)
    open(hpath, "w", encoding="latin-1").write(header)
    open(cpath, "w", encoding="latin-1").write(cnew)
    print("wrote", hpath, "and", cpath)


if __name__ == "__main__":
    main()
